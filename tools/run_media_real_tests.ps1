# tools/run_media_real_tests.ps1
#
# Real playback regression: the decoder pipeline (ffmpeg + waveOut) instead of
# the simulated ticker. Covers, for a local video, a local audio file and a
# remote video:
#   - currentTime advances at wall-clock rate (1.0x) while playing;
#   - pause freezes it, play resumes it;
#   - seek lands on the requested position and playback continues from there;
#   - `ended` fires when the media clock reaches the duration;
#   - the painted picture matches what ffmpeg decodes at the same position
#     (mean colour of the video box vs a reference frame, tolerance 6).
#
# Media used here is exactly what "real playback" was verified against:
#   - the bundled 5 s clip (debug/media/clip640x360.mp4, generated by ffmpeg);
#   - https://artplayer.org/assets/sample/video.mp4;
#   - H:\linsdev\...\432hz颂钵疗愈音乐.mp3 (skipped when the file is absent).
#
# Usage:
#   pwsh -File tools/run_media_real_tests.ps1
#   pwsh -File tools/run_media_real_tests.ps1 -SkipRemote   # no network
#
# Exit code 0 when every assertion passes (skips are not failures).

param(
    [switch]$SkipRemote,
    [switch]$SkipPixels
)

$ErrorActionPreference = 'Stop'

$root    = Split-Path -Parent $PSScriptRoot
$shell   = Join-Path $root 'build-zig-native\agave_shell.exe'
$pages   = Join-Path $root 'tools\pages'
$debug   = Join-Path $root 'debug'
$media   = Join-Path $debug 'media'
$shots   = Join-Path $root 'build-zig-native'
$mp3     = 'H:\linsdev\疗愈师\慈海疗愈师资料归档，卷一，共两卷，2023年9月整理\2022-2月至10月\432hz颂钵疗愈音乐.mp3'
$remote  = 'https://artplayer.org/assets/sample/video.mp4'
$clip    = Join-Path $media 'clip640x360.mp4'

if (-not (Test-Path $shell)) {
    Write-Host "missing $shell (build first: pwsh -File tools/build_project.ps1)"
    exit 1
}

if (-not (Get-Command ffmpeg.exe -ErrorAction SilentlyContinue)) {
    Write-Host 'SKIP: ffmpeg not installed (real playback needs it)'
    exit 0
}

if (-not (Test-Path $media)) { New-Item -ItemType Directory -Path $media | Out-Null }

$failures = 0
$skips    = 0

function Probe {
    param([string]$Query, [string]$Script, [string]$Eval, [int]$Wait = 1200,
          [int]$Settle = 7000, [string]$Shot, [hashtable]$Env)

    $saved = @{}
    if ($Env) {
        foreach ($k in $Env.Keys) { $saved[$k] = [Environment]::GetEnvironmentVariable($k); Set-Item -Path "env:$k" -Value $Env[$k] }
    }

    $args = @('--probe', $Query, '--wait', "$Wait", '--settle', "$Settle")

    if ($Script) { $args += @('--eval-file', $Script) }
    if ($Eval)   { $args += @('--eval', $Eval) }
    if ($Shot)   { $args += @('--shot', $Shot) }

    $output = & $shell @args 2>&1 | Out-String

    if ($Env) {
        foreach ($k in $saved.Keys) {
            if ($null -eq $saved[$k]) { Remove-Item -Path "env:$k" -ErrorAction SilentlyContinue }
            else { Set-Item -Path "env:$k" -Value $saved[$k] }
        }
    }

    $line = ($output -split "`r?`n" | Where-Object { $_ -match '\[exit\]' } | Select-Object -First 1)

    [pscustomobject]@{
        Text = $output
        Exit = if ($line) { ($line -replace '^.*\[exit\]\s*', '') } else { $null }
    }
}

function Check {
    param([string]$Name, $Actual, [scriptblock]$Test, [string]$Expect)

    if ($null -eq $Actual -or $Actual -eq '') {
        Write-Host ("  FAIL {0}: no [exit] line" -f $Name)
        $script:failures++
        return
    }

    if (& $Test $Actual) {
        Write-Host ("  ok   {0}" -f $Name)
    } else {
        Write-Host ("  FAIL {0}: expected {1}" -f $Name, $Expect)
        Write-Host ("       {0}" -f $Actual)
        $script:failures++
    }
}

function Skip {
    param([string]$Name, [string]$Why)
    Write-Host ("  skip {0} ({1})" -f $Name, $Why)
    $script:skips++
}

function Number {
    param($Text, [string]$Pattern)

    if ($Text -match $Pattern) { return [double]$Matches[1] }
    return -1
}

# --- 1. local video: transport and picture ---------------------------------
Write-Host '== local video: play / pause / seek / resume'
$state = (Probe -Query ("$pages\cap_media_real.html?src=../../debug/media/clip640x360.mp4") `
                -Script "$pages\cap_media_real_state.js").Exit

Check 'decoder drives the element' $state { param($t) $t -match 'real=1' } 'real=1'
Check 'clock advances ~1.0x'       $state {
    param($t)
    $adv = Number $t 'advanced=([\d.]+) elapsed=([\d.]+)'
    $adv = Number $t 'play: advanced=([\d.]+)'
    $el  = Number $t 'play: advanced=[\d.]+ elapsed=([\d.]+)'
    ($adv -gt 1.2) -and ($el -gt 0) -and ([math]::Abs($adv - $el) -lt 0.35)
} 'advanced within 0.35 s of elapsed'
Check 'pause freezes the clock'    $state { param($t) $t -match 'pauseDrift=0\.0' } 'pauseDrift=0.0'
Check 'seek lands on target'       $state { param($t) $t -match 'afterSeek: ct=1\.66' } 'afterSeek: ct=1.66x'
Check 'seek does not block'        $state {
    param($t)
    $ms = Number $t 'seekMs=(\d+)'
    ($ms -ge 0) -and ($ms -lt 500)
} 'seekMs < 500'
Check 'resume continues'           $state { param($t) $t -match 'resumed: advanced=0\.[5-9]' } 'resumed: advanced=0.5-0.9'

Write-Host '== local video: ended'
$ended = (Probe -Query ("$pages\cap_media_real.html?src=../../debug/media/clip640x360.mp4") `
                -Script "$pages\cap_media_real_end.js").Exit
Check 'ended transition' $ended { param($t) $t -match 'ended=1 paused=1 ct=5\.000' } 'ended=1 paused=1 ct=5.000'

# --- 2. remote video -------------------------------------------------------
if ($SkipRemote) {
    Skip 'remote video' 'SkipRemote'
} else {
    Write-Host '== remote video: metadata, transport, seek, streaming'
    $enc = [uri]::EscapeDataString($remote)
    # A fresh cache: the streaming assertions only mean something when the
    # body actually has to be fetched during this run.
    $streamCache = Join-Path $shots 'stream-cache'
    if (Test-Path $streamCache) { Remove-Item $streamCache -Recurse -Force }
    New-Item -ItemType Directory -Path $streamCache | Out-Null

    $remoteRun = Probe -Query ("$pages\cap_media_real.html?src=$enc") `
                       -Script "$pages\cap_media_real_state.js" -Wait 3000 -Settle 8000 `
                       -Env @{ AGB_MEDIA_DEBUG = '1'; AGB_MEDIA_CACHE = $streamCache }
    $remoteState = $remoteRun.Exit

    Check 'remote metadata'    $remoteState { param($t) $t -match 'dur=90\.0' } 'dur=90.0'
    Check 'remote decoder'     $remoteState { param($t) $t -match 'real=1' } 'real=1'
    Check 'remote clock'       $remoteState { param($t) $t -match 'play: advanced=1\.' } 'play: advanced=1.x'
    Check 'remote seek to 30'  $remoteState { param($t) $t -match 'afterSeek: ct=30\.0' } 'afterSeek: ct=30.0'

    # Streaming: metadata must be parsed from a copy that is still arriving
    # (done=0), and the first painted frame must precede the end of the
    # download. That is what "play while downloading" means.
    Check 'metadata while downloading' $remoteRun.Text {
        param($t) $t -match 'probe copy: .*done=0.*complete=1'
    } 'probe copy: ... done=0 ... complete=1'

    # The picture needs a decoder on the partial file. (Whether the frame lands
    # before the last byte is a race with the probe's --wait: the page only
    # starts playing when the eval runs, so that ordering is not asserted.)
    Check 'frame from the partial copy' $remoteRun.Text {
        param($t) $t -match 'first frame 640x360'
    } 'first frame 640x360'
}

# --- 2b. playback semantics ------------------------------------------------
Write-Host '== playback semantics: TimeRanges / progress / playbackRate'

$sem = Probe -Query "$pages\cap_media_real.html?src=../../debug/media/clip640x360.mp4" `
             -Wait 1200 -Settle 6000 `
             -Eval "var v=document.getElementById('v'); var ev=[]; v.addEventListener('progress',function(){ev.push('progress');}); v.addEventListener('playing',function(){ev.push('playing');}); v.play(); setTimeout(function(){ var b=v.buffered; probeExit('trEnd='+(typeof b.end)+' trStart='+(typeof b.start)+' len='+b.length+' end='+(b.length?b.end(0).toFixed(2):'-')+' ct='+v.currentTime.toFixed(2)+' ev='+ev.join('/')); }, 1500)"

Check 'TimeRanges has start/end'      $sem.Exit { param($t) $t -match 'trEnd=function' -and $t -match 'trStart=function' } 'trEnd/trStart = function'
Check 'buffered covers a local file'  $sem.Exit { param($t) $t -match 'len=1 end=5\.00' } 'len=1 end=5.00'
Check 'progress fired'                $sem.Exit { param($t) $t -match 'progress' } 'progress in events'

$rate = Probe -Query "$pages\cap_media_real.html?src=../../debug/media/clip640x360.mp4" `
              -Wait 1200 -Settle 6000 `
              -Eval "var v=document.getElementById('v'); v.playbackRate=2.0; v.play(); var t0=(new Date()).getTime(); setTimeout(function(){ probeExit('ct='+v.currentTime.toFixed(2)+' wall='+(((new Date()).getTime()-t0)/1000).toFixed(2)+' rate='+v.playbackRate); }, 1500)"

Check 'playbackRate 2x advances 2x' $rate.Exit {
    param($t)
    $ct = Number $t 'ct=([\d.]+)'
    $wall = Number $t 'wall=([\d.]+)'
    ($ct -gt 0) -and ($wall -gt 0) -and (($ct / $wall) -gt 1.6)
} 'ct/wall > 1.6'

# --- 3. local audio --------------------------------------------------------
if (-not (Test-Path -LiteralPath $mp3)) {
    Skip 'local mp3' 'file not present'
} else {
    Write-Host '== local audio: decoder clock + waveOut evidence'
    $enc = [uri]::EscapeDataString('file:///' + ($mp3 -replace '\\', '/'))

    $audio = Probe -Query ("$pages\cap_media_real.html?kind=audio&src=$enc") `
                   -Script "$pages\cap_media_real_state.js" -Wait 1500 -Settle 8000 `
                   -Env @{ AGB_MEDIA_DEBUG = '1' }

    Check 'audio metadata'    $audio.Exit { param($t) $t -match 'dur=1665\.' } 'dur=1665.x'
    Check 'audio decoder'     $audio.Exit { param($t) $t -match 'real=1' } 'real=1'
    Check 'audio clock'       $audio.Exit { param($t) $t -match 'play: advanced=1\.' } 'play: advanced=1.x'
    Check 'waveOut opened'    $audio.Text { param($t) $t -match 'waveOut=1' } 'waveOut=1'
    Check 'device consumes'   $audio.Text {
        param($t)
        # The device position must track real time: that is what proves the
        # PCM is reaching the sound card, not just being decoded.
        foreach ($line in ($t -split "`r?`n")) {
            if ($line -match 'wall=([\d.]+) device=([\d.]+)') {
                if ([double]$Matches[2] -gt 0.8 -and [math]::Abs([double]$Matches[2] - [double]$Matches[1]) -lt 0.4) { return $true }
            }
        }
        return $false
    } 'device position within 0.4 s of wall clock'
}

# --- 4. direct navigation ---------------------------------------------------
# A bare media URL must open the built-in player (a media document), not a
# download - that is what Chrome does for a top-level .mp4 / .mp3.
Write-Host '== direct navigation: media document'
$clipUrl = 'file:///' + ($clip -replace '\\', '/')

$direct = Probe -Query $clipUrl -Wait 1500 -Settle 5000 -Eval `
    "var v=document.querySelector('video'); probeExit('title='+document.title+' tag='+(v?v.tagName:'-')+' real='+(v?v._agbRealPlayback:'-')+' ct='+(v?v.currentTime.toFixed(2):'-')+' dur='+(v?v.duration:-1))"

Check 'video document, not a download' $direct.Exit {
    param($t) $t -match 'title=clip640x360\.mp4' -and $t -match 'tag=VIDEO' -and $t -match 'real=1'
} 'title=clip640x360.mp4 tag=VIDEO real=1'
Check 'video document plays on its own' $direct.Exit { param($t) $t -match 'ct=1\.' } 'ct=1.x after 1.5 s'
Check 'no download for media MIME' $direct.Text { param($t) $t -notmatch 'download mime' } 'no "[nav] download" line'

if (Test-Path -LiteralPath $mp3) {
    $mp3Url = 'file:///' + ($mp3 -replace '\\', '/')
    $directAudio = Probe -Query $mp3Url -Wait 1500 -Settle 5000 -Eval `
        "var a=document.querySelector('audio'); var r=a.getBoundingClientRect(); probeExit('title='+document.title+' tag='+(a?a.tagName:'-')+' real='+(a?a._agbRealPlayback:'-')+' ct='+(a?a.currentTime.toFixed(2):'-')+' box='+Math.round(r.left)+','+Math.round(r.top)+' '+Math.round(r.width)+'x'+Math.round(r.height))"

    Check 'audio document' $directAudio.Exit {
        param($t) $t -match 'tag=AUDIO' -and $t -match 'real=1' -and $t -match 'ct=1\.'
    } 'tag=AUDIO real=1 ct=1.x'
    Check 'audio document centred' $directAudio.Exit { param($t) $t -match 'box=400,373 300x54' } 'box=400,373 300x54'
} else {
    Skip 'audio document' 'mp3 not present'
}

# A server that lies about the type: "application/octet-stream" for a .mp4 (or
# no Content-Type at all) must still open the player - the extension decides,
# which is what Chrome does too.
if (-not (Get-Command python -ErrorAction SilentlyContinue)) {
    Skip 'octet-stream mp4' 'python not available'
} else {
    $mimeServer = Start-Process -FilePath python `
        -ArgumentList 'tools\media_mime_server.py', '--root', 'debug/media', '--port', '8731' `
        -PassThru -WindowStyle Hidden
    Start-Sleep -Milliseconds 800

    try {
        foreach ($mode in @('octet', 'none')) {
            $r = Probe -Query "http://127.0.0.1:8731/$mode/clip640x360.mp4" -Wait 2500 -Settle 5000 -Eval `
                "var v=document.querySelector('video'); probeExit('tag='+(v?v.tagName:'-')+' real='+(v?v._agbRealPlayback:'-')+' ct='+(v?v.currentTime.toFixed(2):'-')+' dur='+(v?v.duration:-1))"

            Check "$mode Content-Type still plays" $r.Exit {
                param($t) $t -match 'tag=VIDEO' -and $t -match 'real=1' -and $t -match 'ct=[12]\.'
            } 'tag=VIDEO real=1 ct>1'
            Check "$mode Content-Type is not a download" $r.Text { param($t) $t -notmatch 'download mime' } 'no "[nav] download"'
        }
    } finally {
        Stop-Process -Id $mimeServer.Id -Force -ErrorAction SilentlyContinue
    }
}

# --- 5. pixels -------------------------------------------------------------
if ($SkipPixels) {
    Skip 'pixels' 'SkipPixels'
} else {
    Write-Host '== picture matches ffmpeg at the same position'

    $cases = @(
        @{ Name = 'local clip @0.7s'; Query = "$pages\cap_media_real.html?src=../../debug/media/clip640x360.mp4&t=0&hold=1";
           File = $clip; At = 0.7; Shot = "$shots\media_clip_hold.bmp"; Ref = "$media\ref_clip_07.png"; Env = $null },
        @{ Name = 'remote @30.7s';    Query = "$pages\cap_media_real.html?src=$([uri]::EscapeDataString($remote))&t=30&hold=1";
           File = $null; At = 30.7; Shot = "$shots\media_remote_hold.bmp"; Ref = "$media\ref_remote_307.png";
           # Seek to 30 s needs those bytes on disk: reuse the cache the remote
           # section just filled, and take the reference from the same file.
           Env = (Get-Variable -Name streamCache -Scope Script -ErrorAction SilentlyContinue).Value }
    )

    foreach ($c in $cases) {
        if (-not (Test-Path $c.Ref) -and $c.File) {
            & ffmpeg -v error -ss $c.At -i $c.File -frames:v 1 -vf scale=320:180 -y $c.Ref 2>$null
        }

        if (-not $c.File) {
            # Seeking to 30 s needs those bytes on disk. Warm the cache first
            # (one plain probe that lets the download finish), then take the
            # reference from exactly the file the engine will decode.
            if ($c.Env) {
                Probe -Query "$pages\cap_media_real.html?src=$([uri]::EscapeDataString($remote))" `
                      -Eval '0' -Wait 9000 -Settle 9000 -Env @{ AGB_MEDIA_CACHE = $c.Env } | Out-Null
            }

            $dir = if ($c.Env) { $c.Env } else { Join-Path $shots 'media-cache' }
            $cached = Get-ChildItem $dir -Filter *.mp4 -ErrorAction SilentlyContinue |
                      Sort-Object Length -Descending | Select-Object -First 1

            if ($cached -and -not (Test-Path $c.Ref)) {
                & ffmpeg -v error -ss $c.At -i $cached.FullName -frames:v 1 -vf scale=320:180 -y $c.Ref 2>$null
            }
        }

        if (-not (Test-Path $c.Ref)) {
            Skip $c.Name 'no reference frame'
            continue
        }

        $probeEnv = if ($c.Env) { @{ AGB_MEDIA_CACHE = $c.Env } } else { $null }
        $p = Probe -Query $c.Query -Eval '0' -Wait 5000 -Settle 1500 -Shot $c.Shot -Env $probeEnv
        if (-not (Test-Path $c.Shot)) { Skip $c.Name 'no screenshot'; continue }

        $data = & python -c @"
from PIL import Image, ImageStat
a = Image.open(r'$($c.Shot)').convert('RGB').crop((0, 0, 320, 180))
b = Image.open(r'$($c.Ref)').convert('RGB')
ma, mb = ImageStat.Stat(a).mean, ImageStat.Stat(b).mean
print(round(sum(abs(x - y) for x, y in zip(ma, mb)) / 3, 2))
"@ 2>$null

        Check $c.Name $data { param($t) [double]$t -lt 8 } 'average channel distance < 8'
    }
}

Write-Host ''
if ($failures -eq 0) {
    Write-Host ("MEDIA-REAL=PASS ({0} skipped)" -f $skips)
    exit 0
}

Write-Host ("MEDIA-REAL=FAIL ({0} assertion(s), {1} skipped)" -f $failures, $skips)
exit 1
