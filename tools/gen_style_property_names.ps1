# Generates src/javascript/ant_backend/StylePropertyNames.h from CSSPropertyNames.in.
# The list is the camelCase DOM name of every CSS property the engine knows,
# used to build the inline `style` object so that `'prop' in element.style`
# answers like a real CSSStyleDeclaration.
$root = 'E:\mybrowsers\agave'
$input = Join-Path $root 'src\webcore\css\CSSPropertyNames.in'
$output = Join-Path $root 'src\javascript\ant_backend\StylePropertyNames.h'

$evaluator = [System.Text.RegularExpressions.MatchEvaluator] {
    param($m)
    return $m.Groups[1].Value.ToUpper()
}

$names = New-Object System.Collections.Generic.List[string]

foreach ($line in Get-Content $input) {
    $raw = $line.Trim()
    if (-not $raw) { continue }
    if ($raw.StartsWith('#')) { continue }

    $camel = ''
    if ($raw.StartsWith('-webkit-')) {
        $rest = $raw.Substring(8)
        $rest = $rest.Substring(0, 1).ToUpper() + $rest.Substring(1)
        $camel = 'Webkit' + ([regex]::Replace($rest, '-([a-z0-9])', $evaluator))
    } elseif ($raw.StartsWith('-')) {
        # Unknown vendor prefix: keep it as written minus the dashes.
        $camel = $raw.Substring(1)
    } else {
        $camel = [regex]::Replace($raw, '-([a-z0-9])', $evaluator)
    }

    if ($camel -and -not $names.Contains($camel)) { $names.Add($camel) }
}

# Modern spellings the CSS parser aliases onto the -webkit- vocabulary
# (`flex-grow` -> `-webkit-box-flex`, `align-items` -> `-webkit-box-align`, ...).
# Chrome exposes both spellings on computed style, so both need an accessor.
# The table is read from CSSGrammar.y itself: a hand-maintained copy drifted
# and cost getComputedStyle().flexGrow (and flexDirection/flexWrap/transform).
$grammar = Join-Path $root 'src\webcore\css\CSSGrammar.y'
if (Test-Path $grammar) {
    $text = [IO.File]::ReadAllText($grammar)
    $start = $text.IndexOf('aliases[] = {')
    if ($start -ge 0) {
        $end = $text.IndexOf('};', $start)
        if ($end -gt $start) {
            $block = $text.Substring($start, $end - $start)
            foreach ($m in [regex]::Matches($block, '\{\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\}')) {
                $name = $m.Groups[1].Value
                if ($name.StartsWith('-')) { continue }   # vendor-prefixed source alias
                $alias = [regex]::Replace($name, '-([a-z0-9])', $evaluator)
                if ($alias -and -not $names.Contains($alias)) { $names.Add($alias) }
            }
        }
    }
}

# Names Chrome has on computed style that the engine has no property id for
# yet: they answer "" (present but empty), see docs/arch-capability-gaps.md.
$extras = @(
    'cssFloat',
    'alignSelf', 'justifyItems', 'justifySelf', 'placeItems', 'placeContent',
    'placeSelf', 'inset'
)

foreach ($extra in $extras) {
    if (-not $names.Contains($extra)) { $names.Add($extra) }
}

$names.Sort([StringComparer]::Ordinal)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by tools/gen_style_property_names.ps1 from CSSPropertyNames.in.')
[void]$sb.AppendLine(' * camelCase DOM names of every CSS property, used by the inline style object. */')
[void]$sb.AppendLine('#ifndef STYLE_PROPERTY_NAMES_H')
[void]$sb.AppendLine('#define STYLE_PROPERTY_NAMES_H')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('static const char* const kStylePropertyNames[] = {')
foreach ($name in $names) {
    [void]$sb.AppendLine('    "' + $name + '",')
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('static const int kStylePropertyNameCount =')
[void]$sb.AppendLine('    (int)(sizeof(kStylePropertyNames) / sizeof(kStylePropertyNames[0]));')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#endif /* STYLE_PROPERTY_NAMES_H */')

[IO.File]::WriteAllText($output, $sb.ToString())
"generated {0} names -> {1}" -f $names.Count, $output
